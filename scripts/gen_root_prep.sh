#!/usr/bin/env bash
# gen_root_prep.sh - PRINT (never execute) the root preparation block.
#
# Usage (run anywhere; output is pasted into a root shell on the target host):
#   bash gen_root_prep.sh [VERSION] > /tmp/root_prep.sh
#   bash gen_root_prep.sh 19c            # stdout
#
# Environment overrides (all optional):
#   ORACLE_BASE      default /u01/app/oracle
#   ORACLE_HOME      default <ORACLE_BASE>/product/<ver>/dbhome_1
#   UNIX_GROUP       default oinstall
#   DB_GROUP         default dba
#   OPER_GROUP       default oper
#   OS_USER          default oracle
#   PHYSICAL_RAM_MB  default: read from /proc/meminfo on the target
#   VERSION          default 19c  (11g|12c|18c|19c)
#
# SAFETY CONTRACT:
#   - This script executes NOTHING. It only writes text to stdout.
#   - The generated block is idempotent (getent/useradd guards) and marked
#     [ROOT] so a reviewer can see every privileged action.
#   - No passwords, no key material, no automatic /etc/hosts rewrite: the
#     block prints verification commands and a commented example instead.

set -eu

VERSION="${1:-${VERSION:-19c}}"
VERSION="$(printf '%s' "$VERSION" | tr '[:upper:]' '[:lower:]')"

ORACLE_BASE="${ORACLE_BASE:-/u01/app/oracle}"
case "$VERSION" in
  19c) DEFAULT_SUBDIR="product/19.0.0/dbhome_1" ;;
  18c) DEFAULT_SUBDIR="product/18.0.0/dbhome_1" ;;
  12c) DEFAULT_SUBDIR="product/12.2.0.1/dbhome_1" ;;
  11g) DEFAULT_SUBDIR="product/11.2.0/dbhome_1" ;;
  *)
    printf 'ERROR: unsupported VERSION=%s (use 11g|12c|18c|19c)\n' "$VERSION" >&2
    exit 2
    ;;
esac
ORACLE_HOME="${ORACLE_HOME:-${ORACLE_BASE}/${DEFAULT_SUBDIR}}"
UNIX_GROUP="${UNIX_GROUP:-oinstall}"
DB_GROUP="${DB_GROUP:-dba}"
OPER_GROUP="${OPER_GROUP:-oper}"
OS_USER="${OS_USER:-oracle}"

# --- memory-derived kernel parameters -------------------------------------
RAM_MB="${PHYSICAL_RAM_MB:-}"
if [ -z "$RAM_MB" ] && [ -r /proc/meminfo ]; then
  RAM_MB="$(awk '/^MemTotal:/ {print int($2/1024)}' /proc/meminfo)"
fi
if [ -z "$RAM_MB" ]; then
  echo "WARN: cannot read physical memory; emitting placeholders for shmmax/shmall" >&2
  SHMMAX="<RAM_KB_x_0.75_x_1024>"
  SHMALL="<SHMMAX_div_4096>"
  SGA_MB=512
else
  SHMMAX=$(( RAM_MB * 1024 * 1024 * 3 / 4 ))
  SHMALL=$(( SHMMAX / 4096 ))
  # Same formula as references/planning.md: clamp(round(M*0.14), 512, 2048)
  SGA_MB=$(( RAM_MB * 14 / 100 ))
  [ "$SGA_MB" -lt 512 ] && SGA_MB=512
  [ "$SGA_MB" -gt 2048 ] && SGA_MB=2048
fi

cat <<EOF
#!/usr/bin/env bash
# ============================================================================
# Oracle Database ${VERSION} system preparation - RUN AS ROOT ON THE TARGET
# Generated by oracle-db-silent-install / scripts/gen_root_prep.sh
#
# Review every line before executing. Nothing here touches existing data
# directories; every step is idempotent so a re-run is safe.
# ============================================================================
set -eu

echo "[ROOT 1/6] groups and user"
getent group ${UNIX_GROUP} >/dev/null || groupadd -g 54321 ${UNIX_GROUP}
getent group ${DB_GROUP}   >/dev/null || groupadd -g 54322 ${DB_GROUP}
getent group ${OPER_GROUP} >/dev/null || groupadd -g 54323 ${OPER_GROUP}
id ${OS_USER} >/dev/null 2>&1 || useradd -u 54321 -g ${UNIX_GROUP} \\
  -G ${DB_GROUP},${OPER_GROUP} -m -s /bin/bash ${OS_USER}
usermod -a -G ${UNIX_GROUP},${DB_GROUP},${OPER_GROUP} ${OS_USER}
id ${OS_USER}

echo "[ROOT 2/6] directories and ownership"
mkdir -p ${ORACLE_HOME}
mkdir -p $(dirname "${ORACLE_BASE}")/oraInventory
mkdir -p ${ORACLE_BASE}/oradata
mkdir -p ${ORACLE_BASE}/recovery_area
chown -R ${OS_USER}:${UNIX_GROUP} $(dirname "${ORACLE_BASE}")
chmod -R 775 $(dirname "${ORACLE_BASE}")

echo "[ROOT 3/6] hostname resolution (verify, do not blindly rewrite)"
# /etc/hosts must map the FQDN to a NON-loopback IP. Keep the localhost lines.
# Judge by these three, NOT by 'getent hosts' alone (it may show ::1):
hostname -f
getent ahosts "\$(hostname)"
ping -c 1 "\$(hostname)"
# If the FQDN is missing, append one line (backup first) and re-check:
#   cp -p /etc/hosts /etc/hosts.bak.\$(date +%F)
#   echo "<NON_LOOPBACK_IP> \$(hostname) \$(hostname -f)" >> /etc/hosts

echo "[ROOT 4/6] kernel parameters"
cat > /etc/sysctl.d/99-oracle.conf <<'CONF'
fs.aio-max-nr = 1048576
fs.file-max = 6815744
kernel.shmall = ${SHMALL}
kernel.shmmax = ${SHMMAX}
kernel.shmmni = 4096
kernel.sem = 800 640000 400 800
net.ipv4.ip_local_port_range = 9000 65500
net.core.rmem_default = 262144
net.core.rmem_max = 4194304
net.core.wmem_default = 262144
net.core.wmem_max = 1048576
CONF
/sbin/sysctl -p /etc/sysctl.d/99-oracle.conf

echo "[ROOT 5/6] resource limits"
cat > /etc/security/limits.d/99-oracle.conf <<'CONF'
${OS_USER}   soft   nofile   1024
${OS_USER}   hard   nofile   65536
${OS_USER}   soft   nproc    2047
${OS_USER}   hard   nproc    16384
${OS_USER}   soft   stack    10240
${OS_USER}   hard   stack    32768
${OS_USER}   soft   memlock  unlimited
${OS_USER}   hard   memlock  unlimited
CONF
grep -h pam_limits.so /etc/pam.d/sshd /etc/pam.d/login || \\
  echo "WARN: pam_limits.so missing from sshd/login; session limits may not apply"

echo "[ROOT 6/6] prerequisite packages"
if rpm -q oracle-database-preinstall-19c >/dev/null 2>&1; then
  echo "preinstall rpm already present"
else
  yum install -y oracle-database-preinstall-19c || {
    echo "preinstall rpm unavailable; installing the explicit list"
    yum install -y binutils compat-libcap1 compat-libstdc++-33 gcc gcc-c++ \\
      glibc glibc-devel ksh libaio libaio-devel libgcc libstdc++ \\
      libstdc++-devel libXi libXtst make sysstat elfutils-libelf-devel \\
      unixODBC unixODBC-devel unzip || \\
      echo "NOTE: compat-libstdc++-33 is often warning-only on 19c; retry runInstaller with -ignorePrereqFailure"
  }
fi

echo "[DONE] system preparation complete"
echo "Next: as ${OS_USER}, unzip the image-based ${VERSION} zip into ${ORACLE_HOME}"
echo "Memory hint: physical=${RAM_MB:-unknown}MB -> SGA ${SGA_MB}M, PGA $(( SGA_MB / 2 ))M"
EOF
