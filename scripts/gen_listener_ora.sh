#!/usr/bin/env bash
# gen_listener_ora.sh - Write a loopback-bound listener.ora (and optional tnsnames.ora).
#
# Usage (on the target host as the oracle user):
#   bash gen_listener_ora.sh -                       # print listener.ora
#   bash gen_listener_ora.sh "$ORACLE_HOME/network/admin/listener.ora"
#   TNS_OUT="$ORACLE_HOME/network/admin/tnsnames.ora" \
#     bash gen_listener_ora.sh "$ORACLE_HOME/network/admin/listener.ora"
#
# Environment overrides (all optional):
#   BIND_HOST   default 127.0.0.1   (use 0.0.0.0 only if the DB must be reachable)
#   PORT        default 1521
#   SID         default ${ORACLE_SID:-orcl}
#   SERVICE     default the SID; set to the PDB service name for CDB deployments
#   ORACLE_BASE default /u01/app/oracle      (used for ADR_BASE_LISTENER)
#   TNS_OUT     unset by default            (when set, also writes tnsnames.ora)
#
# SAFETY CONTRACT:
#   - Writes only the paths given in $1 and $TNS_OUT (or stdout when $1 is "-").
#   - Backs up an existing listener.ora to <file>.bak.<date> before overwrite.
#   - Does not restart the listener; the caller decides when to reload.

set -eu

OUT="${1:--}"
BIND_HOST="${BIND_HOST:-127.0.0.1}"
PORT="${PORT:-1521}"
SID="${SID:-${ORACLE_SID:-orcl}}"
# TNS aliases are conventionally upper case; Oracle resolves them case-insensitively.
SID="$(printf '%s' "$SID" | tr '[:lower:]' '[:upper:]')"
SERVICE="${SERVICE:-$SID}"
ORACLE_BASE="${ORACLE_BASE:-/u01/app/oracle}"
TNS_OUT="${TNS_OUT:-}"

case "$PORT" in
  ''|*[!0-9]*)
    printf 'ERROR: PORT must be numeric, got "%s"\n' "$PORT" >&2
    exit 2
    ;;
esac

case "$BIND_HOST" in
  127.0.0.1|localhost)
    EXPOSURE="loopback only - not reachable from other hosts"
    ;;
  *)
    EXPOSURE="reachable from other hosts - restrict with firewall rules"
    printf 'WARN: BIND_HOST=%s exposes the listener beyond this host.\n' "$BIND_HOST" >&2
    ;;
esac

listener_body() {
  cat <<EOF
# Generated by oracle-db-silent-install / scripts/gen_listener_ora.sh
# Bind address ${BIND_HOST}:${PORT} -> ${EXPOSURE}
# Reload with: lsnrctl reload   (or: lsnrctl stop && lsnrctl start)
LISTENER =
  (DESCRIPTION_LIST =
    (DESCRIPTION =
      (ADDRESS = (PROTOCOL = TCP)(HOST = ${BIND_HOST})(PORT = ${PORT}))
      (ADDRESS = (PROTOCOL = IPC)(KEY = EXTPROC${PORT}))
    )
  )

ADR_BASE_LISTENER = ${ORACLE_BASE}
EOF
}

tns_body() {
  cat <<EOF
# Generated by oracle-db-silent-install / scripts/gen_listener_ora.sh
# LOCAL_LISTENER resolves through this alias; keep the host identical to
# listener.ora or 'local_listener' will silently fall back to the FQDN.
LISTENER_${SID} =
  (ADDRESS = (PROTOCOL = TCP)(HOST = ${BIND_HOST})(PORT = ${PORT}))

${SERVICE} =
  (DESCRIPTION =
    (ADDRESS = (PROTOCOL = TCP)(HOST = ${BIND_HOST})(PORT = ${PORT}))
    (CONNECT_DATA =
      (SERVER = DEDICATED)
      (SERVICE_NAME = ${SERVICE})
    )
  )
EOF
}

write_or_print() {
  # write_or_print <path-or-"-"> <body-function>
  target="$1"; body="$2"
  if [ "$target" = "-" ]; then
    "$body"
  else
    if [ -f "$target" ]; then
      backup="${target}.bak.$(date +%Y%m%d%H%M%S)"
      cp -p "$target" "$backup"
      printf 'BACKUP=%s\n' "$backup"
    fi
    mkdir -p "$(dirname "$target")"
    "$body" >"$target"
    chmod 644 "$target"
    printf 'WROTE=%s\n' "$target"
  fi
}

write_or_print "$OUT" listener_body
if [ -n "$TNS_OUT" ]; then
  write_or_print "$TNS_OUT" tns_body
fi

if [ "$OUT" != "-" ]; then
  printf '%s\n' '--- effective binding ---'
  printf 'bind=%s port=%s sid=%s service=%s\n' "$BIND_HOST" "$PORT" "$SID" "$SERVICE"
  printf '%s\n' '--- verify after lsnrctl reload ---'
  printf "ss -lntp | grep %s   # expect %s:%s only\n" "$PORT" "$BIND_HOST" "$PORT"
  printf 'tnsping %s\n' "$SERVICE"
fi
